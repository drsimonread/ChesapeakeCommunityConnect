    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'HOST': os.environ['MARIADB_HOST'],
            'PORT': int(db_port),
            'NAME': os.environ['MARIADB_NAME'],
            'USER': os.environ['MARIADB_USER'],
            'PASSWORD': os.environ['MARIADB_PASSWORD'],
            'OPTIONS': {
                'charset': 'utf8mb4',
                'connect_timeout': 5,
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
            },
        }
    }
